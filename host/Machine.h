// A machine: one emulated device, as a driver the Lemus hosts can load (MAME's term is a
// driver). Each host plugin has its own list, the way MAME has a driver list.
#pragma once

#include "Roms.h"

#include <juce_audio_processors/juce_audio_processors.h>

#include <functional>
#include <memory>
#include <vector>

namespace lemus {

enum class Kind { Instrument, Effect };

struct MachineInfo {
	juce::String id;          // stable: saved in sessions, never renamed
	juce::String name;        // the original device, e.g. "Roland TB-303"
	juce::String description; // e.g. "Distortion pedal (1988)"
	Kind kind = Kind::Effect;
	// The ROM images it needs, from the user's ROM folder. None for a circuit-only machine.
	std::vector<RomSpec> roms;
	// Its artwork (optional): the panel's brand marks. Given to `create` in the RomSet: a pack under
	// its name, each place's own file under ArtworkSpec::key (host/Roms.h addArtwork).
	ArtworkSpec artwork;
	// Creates the emulation, given its ROMs. Its parameters are mapped onto the host's slots in
	// order.
	std::function<std::unique_ptr<juce::AudioProcessor>(const RomSet &)> create;
	// Its outputs after the main one (a drum machine's individual outs), named. The machine's own
	// plugin declares them, off until the host turns them on, each mono or stereo, and the machine
	// takes the same layout. Hosts with several machines have the main output only.
	std::vector<juce::String> outputs = {};
	// Those outputs as stereo pairs (a synth's OUT 2 and OUT 3) rather than mono jacks.
	bool stereoOutputs = false;
	// An instrument's audio input (a synth's external inputs), named; empty for none. The machine's
	// own plugin declares it as a stereo side-chain, off until the host routes something to it, and
	// the machine takes the same layout. The machine reads it only while the host has it on: with
	// nothing routed, some hosts hand an instrument its own last output there. Hosts with several
	// machines have none.
	juce::String sideChain = {};
};

// A driver as a host's list holds it: with the name its own plugin ships under (from machine.cmake,
// by the generated list).
inline MachineInfo withPluginName(MachineInfo machine, const char *plugin)
{
	machine.artwork.plugin = plugin;
	return machine;
}

// The machines built into this host: machines/<host>.cpp, or machines/only_<id>.cpp in a machine's
// own plugin (generated by CMakeLists.txt).
const std::vector<MachineInfo> &machines();

inline const MachineInfo *findMachine(const juce::String &id)
{
	for (const auto &m : machines())
		if (m.id == id)
			return &m;
	return nullptr;
}

} // namespace lemus
