/*********************************************************************

    Portable Motorola 6809 emulator

**********************************************************************/
// Ported from MAME (src/devices/cpu/m6809, master c2caa8969adbf3d599a655a162a6eac163fa63bc). MAME's
// licence and copyright notice are kept above. Changes for Lemus: the device framework is replaced
// by plain members (a Bus for memory, run(cycles), setInput()); the HD6309/Konami variants, the
// debugger interface and save states are left out; HALT is added as an input that stops the CPU at
// the next instruction boundary, as the MC6809 does. The opcode switch m6809.hxx is generated by
// tools/port_m6809.py from MAME's m6809.lst.

#pragma once

#include <cstdint>

namespace xpander {

class M6809
{
public:
    // The CPU's view of its board. Every access is one bus cycle (one E cycle).
    struct Bus
    {
        virtual ~Bus() = default;
        virtual uint8_t read(uint16_t address) = 0;
        virtual void write(uint16_t address, uint8_t data) = 0;
        // The interrupt-acknowledge cycle (BA low, BS high) while the vector is fetched.
        virtual void interruptAcknowledge(int /*line*/) {}
    };

    enum Line { IRQ = 0, FIRQ = 1, NMI = 2 };

    explicit M6809(Bus& bus) : m_bus(&bus) {}
    // Addresses from `from` up are plain ROM (reads without side effects): read from `base` directly.
    void setRom(uint16_t from, const uint8_t* base)
    {
        m_romFrom = from;
        m_romBase = base;
    }
    // Reads below `limit` come straight from `base` (RAM with no read side effects).
    void setRam(uint32_t limit, const uint8_t* base)
    {
        m_ramLimit = limit;
        m_ramBase = base;
    }

    void reset();
    // Runs at least `cycles` bus cycles (E cycles), finishing the step in progress; returns the
    // cycles used. While halted (HALT low at an instruction boundary) the cycles pass idle.
    int run(int cycles);
    void setInput(Line line, bool asserted);
    void setHalt(bool asserted) { m_haltLine = asserted; }
    // BA: high while halted (the bus is released), as the Xpander's bus bridge sees it.
    bool busAvailable() const { return m_halted; }
    uint16_t pc() const { return m_pc.w; }
    uint64_t totalCycles() const { return m_total; }
    // The bus cycle in progress, counted from power-on: valid inside a Bus callback during run().
    uint64_t now() const { return m_total + uint64_t(m_runCycles - m_icount); }

private:
    union PAIR16
    {
        struct { uint8_t l, h; } b;
        struct { int8_t l, h; } sb;
        uint16_t w;
        int16_t sw;
    };
    static_assert(sizeof(PAIR16) == 2, "PAIR16");

    union M6809Q
    {
        union
        {
            struct { uint8_t f, e, b, a; };
            struct { uint16_t w, d; };
        } r;
        struct { PAIR16 w, d; } p;
        uint32_t q;
    };

    enum
    {
        ADDRESSING_MODE_IMMEDIATE = 0,
        ADDRESSING_MODE_EA = 1,
        ADDRESSING_MODE_REGISTER_A = 2,
        ADDRESSING_MODE_REGISTER_B = 3,
        ADDRESSING_MODE_REGISTER_D = 4
    };

    enum
    {
        CC_C = 0x01, CC_V = 0x02, CC_Z = 0x04, CC_N = 0x08,
        CC_I = 0x10, CC_H = 0x20, CC_F = 0x40, CC_E = 0x80
    };

    enum
    {
        CC_VC = CC_V | CC_C,
        CC_ZC = CC_Z | CC_C,
        CC_NZ = CC_N | CC_Z,
        CC_NZC = CC_N | CC_Z | CC_C,
        CC_NZV = CC_N | CC_Z | CC_V,
        CC_NZVC = CC_N | CC_Z | CC_V | CC_C,
        CC_HNZVC = CC_H | CC_N | CC_Z | CC_V | CC_C
    };

    enum
    {
        VECTOR_SWI3 = 0xFFF2,
        VECTOR_SWI2 = 0xFFF4,
        VECTOR_FIRQ = 0xFFF6,
        VECTOR_IRQ = 0xFFF8,
        VECTOR_SWI = 0xFFFA,
        VECTOR_NMI = 0xFFFC,
        VECTOR_RESET_FFFE = 0xFFFE
    };

    enum
    {
        EXCEPTION_SWI = 1, EXCEPTION_SWI2 = 2, EXCEPTION_SWI3 = 3,
        EXCEPTION_XFIRQ = 4, EXCEPTION_XRES = 5
    };

    // The names MAME's opcode list uses for the framework, as no-ops or plain calls.
    enum { CLEAR_LINE = 0, ASSERT_LINE = 1, INPUT_LINE_NMI = NMI, M6809_IRQ_LINE = IRQ,
           M6809_FIRQ_LINE = FIRQ };
    struct NoLine { void operator()(int) const {} };
    NoLine m_lic_func, m_syncack_write_func;
    void debugger_instruction_hook(uint16_t) {}
    void debugger_exception_hook(int) {}
    void debugger_wait_hook() {}
    void standard_irq_callback(int line, uint16_t) { m_bus->interruptAcknowledge(line); }
    [[noreturn]] static void fatalerror(const char*);

    Bus* m_bus;
    uint32_t m_romFrom = 0x10000;
    const uint8_t* m_romBase = nullptr;
    uint32_t m_ramLimit = 0;
    const uint8_t* m_ramBase = nullptr;
    uint8_t busRead(uint16_t address)
    {
        if (address >= m_romFrom)
            return m_romBase[address - m_romFrom];
        if (address < m_ramLimit)
            return m_ramBase[address];
        return m_bus->read(address);
    }

    // CPU registers
    PAIR16 m_pc {};
    PAIR16 m_ppc {};
    M6809Q m_q {};
    PAIR16 m_x {}, m_y {};
    PAIR16 m_u {}, m_s {};
    uint8_t m_dp = 0;
    uint8_t m_cc = 0;
    PAIR16 m_temp {};
    uint8_t m_opcode = 0;

    // other internal state
    uint8_t* m_reg8 = nullptr;
    PAIR16* m_reg16 = nullptr;
    bool m_nmi_line = false;
    bool m_nmi_asserted = false;
    bool m_firq_line = false;
    bool m_irq_line = false;
    bool m_lds_encountered = false;
    int m_icount = 0;
    int m_addressing_mode = 0;
    PAIR16 m_ea {};
    uint32_t m_state = 0;
    bool m_cond = false;
    bool m_free_run = false;

    bool m_haltLine = false;
    bool m_halted = false;
    uint64_t m_total = 0;
    int m_runCycles = 0;

    void eat(int cycles) { m_icount -= cycles; }
    void eat_remaining();

    uint8_t read_memory(uint16_t address) { eat(1); return busRead(address); }
    void write_memory(uint16_t address, uint8_t data) { eat(1); m_bus->write(address, data); }
    uint8_t read_opcode(uint16_t address) { eat(1); return busRead(address); }
    uint8_t read_opcode_arg(uint16_t address) { eat(1); return busRead(address); }
    uint8_t read_opcode() { return read_opcode(m_pc.w++); }
    uint8_t read_opcode_arg() { return read_opcode_arg(m_pc.w++); }
    void dummy_read_opcode_arg(uint16_t delta) { read_opcode_arg(uint16_t(m_pc.w + delta)); }
    // $FFFF is ROM on both boards (the vectors): a read with no side effect, so only its cycles count.
    void dummy_vma(int count) { eat(count); }

    void push_state(uint16_t state) { m_state = (m_state << 9) | state; }
    uint16_t pop_state() { uint16_t result = m_state & 0x1ff; m_state >>= 9; return result; }
    void reset_state() { m_state = 1; }

    uint8_t read_ea() { return read_memory(m_ea.w); }
    void write_ea(uint8_t data) { write_memory(m_ea.w, data); }
    void set_ea(uint16_t ea) { m_ea.w = ea; m_addressing_mode = ADDRESSING_MODE_EA; }
    void set_ea_h(uint8_t ea_h) { m_ea.b.h = ea_h; }
    void set_ea_l(uint8_t ea_l) { m_ea.b.l = ea_l; m_addressing_mode = ADDRESSING_MODE_EA; }

    uint8_t read_operand();
    uint8_t read_operand(int ordinal);
    uint8_t read_vector(int ordinal) { return read_memory(uint16_t(m_ea.w + ordinal)); }
    void write_operand(uint8_t data);
    void write_operand(int ordinal, uint8_t data);

    void daa();
    void mul();

    void nop() {}
    template <class T> T rotate_right(T value);
    template <class T> uint32_t rotate_left(T value);
    void set_a() { m_addressing_mode = ADDRESSING_MODE_REGISTER_A; }
    void set_b() { m_addressing_mode = ADDRESSING_MODE_REGISTER_B; }
    void set_d() { m_addressing_mode = ADDRESSING_MODE_REGISTER_D; }
    void set_imm() { m_addressing_mode = ADDRESSING_MODE_IMMEDIATE; }
    void set_regop8(uint8_t& reg) { m_reg8 = &reg; m_reg16 = nullptr; }
    void set_regop16(PAIR16& reg) { m_reg16 = &reg; m_reg8 = nullptr; }
    uint8_t& regop8() { return *m_reg8; }
    PAIR16& regop16() { return *m_reg16; }
    bool is_register_register_op_16_bit() { return m_reg16 != nullptr; }
    bool add8_sets_h() { return true; }
    static constexpr bool hd6309_native_mode() { return false; }

    uint16_t& ireg();

    template <class T> T set_flags(uint8_t mask, T a, T b, uint32_t r);
    template <class T> T set_flags(uint8_t mask, T r);

    bool cond_hi() { return !(m_cc & CC_ZC); }
    bool cond_cc() { return !(m_cc & CC_C); }
    bool cond_ne() { return !(m_cc & CC_Z); }
    bool cond_vc() { return !(m_cc & CC_V); }
    bool cond_pl() { return !(m_cc & CC_N); }
    bool cond_ge() { return (m_cc & CC_N ? true : false) == (m_cc & CC_V ? true : false); }
    bool cond_gt() { return cond_ge() && !(m_cc & CC_Z); }
    void set_cond(bool cond) { m_cond = cond; }
    bool branch_taken() { return m_cond; }

    bool firq_saves_entire_state() { return false; }
    uint16_t partial_state_registers() { return 0x81; }
    uint16_t entire_state_registers() { return 0xFF; }

    uint16_t read_tfr_exg_816_register(uint8_t reg);
    uint16_t read_exg_168_register(uint8_t reg);
    void write_exgtfr_register(uint8_t reg, uint16_t value);
    bool is_register_addressing_mode();
    bool is_ea_addressing_mode() { return m_addressing_mode == ADDRESSING_MODE_EA; }
    uint16_t get_pending_interrupt();
    void log_illegal() {}

    void execute_one();
};

} // namespace xpander
