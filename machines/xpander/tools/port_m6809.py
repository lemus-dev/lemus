#!/usr/bin/env python3
"""Builds core/m6809/m6809.hxx from MAME's MC6809 core in private/docs/mame/cpu/m6809
(BSD-3-Clause; core by Nathan Woods, opcode-list generator m6809make.py by Olivier Galibert).

MAME writes the 6809's instructions as a list (m6809.lst, which includes base6x09.lst) and turns it
into one big resumable switch with m6809make.py. This script does the same transformation (it is a
re-implementation of m6809make.py's rules, run here so no downloaded code is executed):

- `%NAME` dispatches to the label NAME; a state number is pushed so execution resumes after it.
- `%NAME*` dispatches to NAME16 or NAME8, by is_register_register_op_16_bit().
- A line starting with `@` eats a cycle: if the cycle budget is used up, the state is pushed and
  execute_one() returns, to resume at the next line.
- The output is the case table followed by the code, included inside `switch (pop_state())` in
  core/m6809/m6809.cpp.

The core class (m6809.h, m6809.cpp) is MAME's m6809_base_device with the device framework
replaced by plain members; it provides the names the list uses (debugger hooks, interrupt
acknowledge, LIC and sync-acknowledge lines). Re-run after updating the MAME sources:

    python3 tools/port_m6809.py [MAME_M6809_DIR] [OUT_HXX]
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "private/docs/mame/cpu/m6809")
DST = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "core/m6809/m6809.hxx")

HEADER = """// license:BSD-3-Clause
// copyright-holders:Nathan Woods, Olivier Galibert
// Generated by tools/port_m6809.py from MAME's src/devices/cpu/m6809/m6809.lst and base6x09.lst
// (the transformation of MAME's m6809make.py). Do not edit; re-run the script.
"""


def load(path, out):
    base = os.path.dirname(path)
    with open(path) as f:
        raw = re.split(r"(\n|; *\n?)", f.read())
    i = 0
    while i < len(raw) - 1:
        line = raw[i] + raw[i + 1]
        if line.startswith("#include"):
            load(os.path.join(base, line.split('"')[1]), out)
        else:
            out.append(line)
        i += 2


def generate(lines):
    to_state = {"MAIN": 0, "INTERRUPT_VECTOR": 1}
    from_state = {0: "MAIN", 1: "INTERRUPT_VECTOR"}
    state = len(from_state)
    text = []
    dispatch_re = re.compile(r"([A-Za-z0-9\t ]+\:)*\s*\%")
    i = 0
    while i < len(lines):
        line = lines[i]
        ws = line[: len(line) - len(line.lstrip())]
        next_return = i + 1 == len(lines) or lines[i + 1].strip() == "return;"
        next_dispatch_return = (i + 1 < len(lines) and dispatch_re.match(lines[i + 1])
                                and i + 2 < len(lines) and lines[i + 2].strip() == "return;")
        if dispatch_re.match(line):
            pos = line.find("%")
            target = line[pos + 1:].strip("\t\n; ")
            label = line[:pos].strip()
            if label:
                text.append(ws + label + "\n")
                ws += "\t"
            if target.endswith("*"):
                goto = ("if (is_register_register_op_16_bit()) goto %s16; else goto %s8;\n"
                        % (target[:-1], target[:-1]))
            else:
                goto = "goto %s;\n" % target
            if next_return:
                text.append(ws + goto)
                i += 1
            elif next_dispatch_return:
                pos2 = lines[i + 1].find("%")
                nxt = lines[i + 1][pos2 + 1:].strip("\t\n; ")
                if nxt not in to_state:
                    to_state[nxt] = state
                    from_state[state] = nxt
                    state += 1
                text.append(ws + "push_state(%s);\t// %s\n" % (to_state[nxt], nxt))
                text.append(ws + goto)
                i += 2
            else:
                text.append(ws + "push_state(%s);\n" % state)
                text.append(ws + goto)
                text.append("state_%s:\n" % state)
                state += 1
        else:
            check = line.lstrip().startswith("@")
            if check:
                line = line.replace("@", "", 1)
            text.append(line)
            if check and not next_return:
                text.append(ws + "if (UNEXPECTED(m_icount <= 0)) { push_state(%s); return; }\n" % state)
                text.append("state_%s:\n" % state)
                state += 1
        i += 1
    cases = ["\tcase %d:\tgoto %s;\n" % (s, from_state.get(s, "state_%d" % s)) for s in range(state)]
    cases.append('\tdefault:\n\t\tfatalerror("Unexpected state");\n\t\tbreak;\n\n')
    return "".join(cases) + "".join(text)


def main():
    lines = []
    load(os.path.join(SRC, "m6809.lst"), lines)
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w") as f:
        f.write(HEADER + generate(lines))
    print("wrote", DST)


if __name__ == "__main__":
    main()
