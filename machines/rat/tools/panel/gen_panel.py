#!/usr/bin/env python3
"""docs/panel.json -> plugin/PanelData.h: the measured 1984 RAT White Face as C++ constants.

Usage (from the machine folder): ../../.venv/bin/python -I tools/panel/gen_panel.py

All lengths are mm in panel.json's plan frame (origin: rear-left corner of the outline, x right, y
towards the player); angles in degrees from 12 o'clock, clockwise. The brand marks have no
outlines here: they are artwork places, filled from the user's own files."""
import json, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def f(v):
    return "%.3ff" % float(v)


def rect(name, r, comment=""):
    c = f"  // {comment}" if comment else ""
    return f"constexpr Rect {name}{{{f(r['x0'])}, {f(r['y0'])}, {f(r['x1'])}, {f(r['y1'])}}};{c}"


def argb(hexrgb):
    return "0xff" + hexrgb.lstrip("#").lower() + "u"


def main():
    d = json.load(open(os.path.join(ROOT, "docs/panel.json")))
    o = []
    o.append("// Generated by tools/panel/gen_panel.py from docs/panel.json: the 1984 ProCo RAT \"White Face\"")
    o.append("// measured from " + d["source_image"] + ".")
    o.append("// mm, plan view; origin the rear-left corner of the outline, x right, y towards the player;")
    o.append("// degrees from 12 o'clock, clockwise. Scale +-%.1f %% (docs/panel.md)." % d["scale"]["uncertainty_pct"])
    o.append("#pragma once")
    o.append("")
    o.append("#include <cstdint>")
    o.append("")
    o.append("namespace ratpanel {")
    o.append("")
    o.append("struct Rect {")
    o.append("\tfloat x0, y0, x1, y1;")
    o.append("\tfloat w() const { return x1 - x0; }")
    o.append("\tfloat h() const { return y1 - y0; }")
    o.append("};")
    o.append("")
    o.append(f"constexpr float kWidth = {f(d['outline']['w'])}, kDepth = {f(d['outline']['h'])};")
    ch, gp, sh = d["cheeks"], d["gaps"], d["shell_top"]
    o.append(rect("kCheekLeft", {"x0": ch["left"]["x0"], "x1": ch["left"]["x1"], "y0": ch["y0"], "y1": ch["y1"]}, "the cheeks' top edges"))
    o.append(rect("kCheekRight", {"x0": ch["right"]["x0"], "x1": ch["right"]["x1"], "y0": ch["y0"], "y1": ch["y1"]}))
    o.append(rect("kGapLeft", {"x0": gp["left"][0], "x1": gp["left"][1], "y0": sh["y0"], "y1": sh["y1"]}, "between cheek and shell"))
    o.append(rect("kGapRight", {"x0": gp["right"][0], "x1": gp["right"][1], "y0": sh["y0"], "y1": sh["y1"]}))
    o.append(rect("kShellTop", sh, "the top plate; its rear and front edges bend down"))
    o.append("")
    lb = d["legend_box"]
    o.append(rect("kLegendBox", lb, "stroke centre lines"))
    o.append(f"constexpr float kLegendStroke = {f(lb['stroke'])};")
    o.append(f"constexpr float kLegendDivs[2] = {{{f(lb['divs'][0])}, {f(lb['divs'][1])}}};")
    o.append("struct Label {")
    o.append("\tconst char *text;")
    o.append("\tRect ink; // the letters' measured ink box")
    o.append("};")
    o.append("constexpr Label kLabels[3] = {")
    for l in d["labels"]:
        o.append(f"\t{{\"{l['text']}\", {{{f(l['x0'])}, {f(l['y0'])}, {f(l['x1'])}, {f(l['y1'])}}}}},")
    o.append("};")
    o.append("")
    o.append("struct Scale {")
    o.append("\tfloat cx, cy, r, stroke; // the knob's shaft is the centre")
    o.append("};")
    o.append("constexpr Scale kScales[3] = {")
    for s in d["scales"]:
        o.append(f"\t{{{f(s['cx'])}, {f(s['cy'])}, {f(s['r'])}, {f(s['stroke'])}}}, // {s['name']}")
    o.append("};")
    o.append(f"constexpr float kArcDeg[2] = {{{f(d['scales'][0]['arc_deg'][0])}, {f(d['scales'][0]['arc_deg'][1])}}};")
    o.append("constexpr float kTickDeg[7] = {" + ", ".join(f(x) for x in d["scales"][0]["tick_deg"]) + "};")
    o.append(f"constexpr float kTickW = {f(d['tick_w'])}, kTickRIn = {f(d['tick_r_in'])}; // the knob hides the ticks' inner ends")
    o.append("")
    k = d["knobs"]
    o.append("struct KnobSpec {")
    o.append("\tfloat skirtD, topD, height, pointerR0, pointerR1, pointerW, minDeg, maxDeg;")
    o.append("};")
    o.append(f"constexpr KnobSpec kKnob{{{f(k['skirt_d'])}, {f(k['top_d'])}, {f(k['height'])}, {f(k['pointer_r0'])}, "
             f"{f(k['pointer_r1'])}, {f(k['pointer_w'])}, {f(k['travel_deg'][0])}, {f(k['travel_deg'][1])}}};")
    o.append("")
    rb = d["rat_box"]
    o.append(rect("kRatBox", rb, "stroke centre lines"))
    o.append(f"constexpr float kRatBoxStroke = {f(rb['stroke'])};")
    o.append(rect("kWhiteBlock", d["white_block"]))
    o.append(rect("kPlaceRat", d["places"]["rat"], "the RAT letters' box (artwork place rat)"))
    o.append(rect("kPlaceProco", d["places"]["proco"], "the Pro Co logo's box in the block (artwork place proco)"))
    o.append("")
    fs = d["footswitch"]
    o.append("struct FootswitchSpec {")
    o.append("\tfloat x, y, bezelD, plungerD, plungerH;")
    o.append("};")
    o.append(f"constexpr FootswitchSpec kFootswitch{{{f(fs['x'])}, {f(fs['y'])}, {f(fs['bezel_d'])}, {f(fs['plunger_d'])}, {f(fs['plunger_top_h'])}}};")
    o.append("")
    fr = d["front_face"]
    p = fr["place_front"]
    o.append(f"constexpr float kFrontHeight = {f(fr['height'])}; // the front face, from the top plate's bend down to the base")
    o.append(f"constexpr Rect kPlaceFront{{{f(p['x0'])}, {f(p['z0'])}, {f(p['x1'])}, {f(p['z1'])}}}; // x as the top; y down the face (artwork place front)")
    o.append("")
    c = d["colours"]
    o.append("// Colours measured on the photo (soft light from above).")
    for key, name in [("plate", "kPlate"), ("block_white", "kBlockWhite"), ("print_white", "kPrintWhite"), ("cheek", "kCheek"),
                      ("gap", "kGap"), ("knob_top", "kKnobTop"), ("plunger", "kPlunger"), ("chrome", "kChrome")]:
        o.append(f"constexpr uint32_t {name} = {argb(c[key])};")
    o.append("")
    o.append("} // namespace ratpanel")
    open(os.path.join(ROOT, "plugin/PanelData.h"), "w").write("\n".join(o) + "\n")
    print("wrote plugin/PanelData.h")


if __name__ == "__main__":
    main()
