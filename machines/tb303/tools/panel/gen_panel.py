#!/usr/bin/env python3
"""docs/panel.json -> plugin/PanelData.h: the measured front panel as a C++ table.

Usage: gen_panel.py docs/panel.json plugin/PanelData.h"""
import json, sys

TYPES = {"case": "Case", "region": "Region", "fill": "Fill", "outline": "Outline", "line": "Line",
         "label_box": "LabelBox", "outline_box": "OutlineBox", "text": "Text", "symbol": "Symbol",
         "logo": "Logo", "knob": "Knob", "rotary_switch": "Switch", "button": "Button", "led": "Led"}


def font_of(f):
    f = (f or "").lower()
    if "segno" in f:
        return "Segno"
    if "times bold italic" in f:
        return "TimesBoldItalic"
    if "times" in f:
        return "TimesBold"
    if "regular" in f:
        return "HelvRegular"
    if "bold" in f:
        return "HelvBold"
    return "HelvMedium"


def argb(colours, key):
    if key is None:
        return "0x00000000"
    h = colours[key]["hex"].lstrip("#")
    return "0xff" + h.lower()


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    src, out = sys.argv[1:3]
    d = json.load(open(src))
    colours = d["colours"]
    rows, points = [], []
    for e in d["elements"]:
        t = TYPES[e["type"]]
        if "bbox" in e:
            x0, y0, x1, y1 = e["bbox"]
        else:
            w = e.get("w", e.get("d", 0)); h = e.get("h", e.get("d", 0))
            x0, y0, x1, y1 = e["x"] - w / 2, e["y"] - h / 2, e["x"] + w / 2, e["y"] + h / 2
        if t in ("Knob", "Switch", "Led"):
            dd = e["d"]
            x0, y0, x1, y1 = e["x"] - dd / 2, e["y"] - dd / 2, e["x"] + dd / 2, e["y"] + dd / 2
        p0, pn = len(points) // 2, 0
        if t == "Line":
            for x, y in e["points"]:
                points += [x, y]
            pn = len(e["points"])
        extra = 0.0
        if t == "Knob":
            extra = e["knob_d"]
        elif t == "Switch":
            extra = e["knob_d"]
        elif t == "Button":
            extra = 1.0 if e.get("style") == "wide" else 0.0
        rows.append("\t{PType::%s, %s, %s, %.3ff, %.3ff, %.3ff, %.3ff, %.3ff, %.3ff, %su, %su, PFont::%s, %.3ff, %d, %d, %.3ff}," % (
            t, cstr(e["id"]), cstr(str(e.get("label", ""))), x0, y0, x1, y1,
            float(e.get("corner_r") or 0), float(e.get("stroke") or e.get("tick_w") or 0),
            argb(colours, e.get("colour")), argb(colours, e.get("text_colour")),
            font_of(e.get("font")), float(e.get("cap_h") or 0), p0, pn, extra))
    with open(out, "w") as f:
        f.write("// Generated by tools/panel/gen_panel.py from docs/panel.json: the TB-303 top panel,\n")
        f.write("// measured from the CC0 top-down photo. Coordinates in mm from the rear-left corner.\n")
        f.write("#pragma once\n\n#include <cstdint>\n\nnamespace panel {\n\n")
        f.write("enum class PType { Case, Region, Fill, Outline, Line, LabelBox, OutlineBox, Text, Symbol, Logo, Knob, Switch, Button, Led };\n")
        f.write("enum class PFont { HelvMedium, HelvBold, HelvRegular, TimesBold, TimesBoldItalic, Segno };\n\n")
        f.write("struct Element {\n\tPType type;\n\tconst char *id, *label;\n\tfloat x0, y0, x1, y1;\n\tfloat corner, stroke;\n"
                "\tuint32_t colour, textColour;\n\tPFont font;\n\tfloat capH;\n\tint pointStart, pointCount;\n"
                "\tfloat extra; // knob/switch body diameter; 1 for wide keys\n};\n\n")
        f.write("constexpr float kWidth = %.1ff, kHeight = %.1ff;\n\n" % (d["panel"]["w"], d["panel"]["h"]))
        f.write("inline const float points[] = {\n\t" + ", ".join("%.3ff" % p for p in points) + "\n};\n\n")
        f.write("inline const Element elements[] = {\n" + "\n".join(rows) + "\n};\n\n")
        f.write("constexpr int kElementCount = %d;\n\n" % len(rows))
        for k, v in colours.items():
            f.write("constexpr uint32_t %s = %s;\n" % ("c_" + k, argb(colours, k)))
        f.write("\n} // namespace panel\n")
    print(len(rows), "elements")


if __name__ == "__main__":
    main()
