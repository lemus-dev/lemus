#!/usr/bin/env python3
"""docs/boards.json -> plugin/BoardData.h: the main and switch boards' parts as a C++ table.

Usage: gen_boards.py docs/boards.json plugin/BoardData.h"""
import json, math, sys

KINDS = {"R": "R", "C": "C", "CE": "CE", "D": "D", "ZD": "ZD", "Q": "Q", "L": "L", "JW": "JW", "WP": "WP",
         "IC": "IC", "SIP": "SIP", "VR": "VR", "TM": "TM", "TP": "TP", "S": "S", "J": "J", "HOLE": "Hole",
         "TXT": "Txt"}


def f(v):
    return "NAN" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{v:.2f}f"


def centre(p):
    if "centre" in p:
        return p["centre"]
    if "box" in p:
        b = p["box"]
        return [(b[0] + b[2]) / 2, (b[1] + b[3]) / 2]
    if p.get("pads"):
        return [sum(q[0] for q in p["pads"]) / len(p["pads"]), sum(q[1] for q in p["pads"]) / len(p["pads"])]
    return p["text"]


def row(p):
    k = p["kind"]
    cx, cy = centre(p)
    a = b = q = (None, None)
    pads = p.get("pads", [])
    boxed = k in ("IC", "SIP", "S", "J") or (k == "Q" and "flat" not in p)
    if "box" in p and (boxed or len(pads) < 2):
        a, b = p["box"][:2], p["box"][2:]
    elif len(pads) >= 2:
        a, b = pads[0], pads[-1]
        if len(pads) == 3:
            q = pads[1]
    elif len(pads) == 1:
        a = pads[0]
    size = p.get("dia", p.get("size", p.get("pins", 0)))
    lying = False
    if k == "CE" and "box" in p:
        bx = p["box"]
        w, h = abs(bx[2] - bx[0]), abs(bx[3] - bx[1])
        size = min(w, h) if "dia" not in p else size
        if max(w, h) > 1.6 * min(w, h):
            # Lying on its side: the can's box in a, b.
            lying = True
            a, b, q = bx[:2], bx[2:], (None, None)
    d = ""
    if lying:
        d = "L"
    elif k == "Q":
        d = p.get("flat", "") or "B"
    elif k == "IC":
        d = p.get("notch", "")
    elif k == "CE" and "plus" in p:
        d = "a" if p["plus"] == 0 else "b"
    elif k in ("D", "ZD") and p.get("cathodeKnown", True):
        d = "k"
    t = p.get("text", [None, None])
    esc = lambda v: v.replace("\\", "\\\\").replace('"', '\\"')
    ref, label = esc(p["ref"]), esc(p.get("printed", p["ref"]))
    return (f'\t{{Kind::{KINDS[k]}, "{ref}", "{label}", {"true" if p["board"] == "switch" else "false"}, {f(cx)}, {f(cy)}, '
            f'{f(a[0])}, {f(a[1])}, {f(b[0])}, {f(b[1])}, {f(q[0])}, {f(q[1])}, {f(float(size))}, '
            f"{repr(d) if d else '0'}, {f(t[0])}, {f(t[1])}, {int(p.get('rot', 0))}}},")


def main():
    src, out = sys.argv[1], sys.argv[2]
    data = json.load(open(src))
    # Copper-side text the drawing shows through the board isn't seen from above.
    parts = [p for p in data["parts"] if not p.get("mirrored") and p.get("ref") != "OUTLINE"]
    parts = sorted(parts, key=lambda p: (p["board"] != "main", p["kind"], p["ref"]))
    outlines = []
    for name in ("main", "switch"):
        pts = data["outlines"][name]
        outlines.append(f"inline constexpr float k{name.capitalize()}Outline[] = {{" + ", ".join(f"{f(x)}, {f(y)}" for x, y in pts) + "};")
    lines = [
        "// Generated by tools/panel/gen_boards.py from docs/boards.json: the TB-303's main and switch",
        "// boards as the service notes draw them (p.6, view from component side), in the panel's mm.",
        "#pragma once",
        "",
        "#include <cmath>",
        "",
        "namespace board {",
        "",
        "enum class Kind { R, C, CE, D, ZD, Q, L, JW, WP, IC, SIP, VR, TM, TP, S, J, Hole, Txt };",
        "",
        "// One part, its designator (ref; \"?\" when none is printed) and what the board prints for it",
        "// (label: often the bare number, \"66\" for R66). Two-lead parts have pads a and b (a diode's",
        "// cathode is a when dir is 'k'); a",
        "// transistor's third pad is q (the middle lead) and dir is the side its flat faces (N E S W),",
        "// or 'B' when drawn as a box (a, b); ICs, switches, jacks and SIPs have their box in a, b and an",
        "// IC's dir is its notch's side; an electrolytic's dir says which pad is + ('a' or 'b'), or is 'L'",
        "// when it lies on its side with its can's box in a, b. size is",
        "// a round part's diameter, an IC's pin count, a text's cap height. tx, ty is the printed",
        "// designator (NAN: none), rot its rotation in degrees (90: reads bottom to top).",
        "struct Part {",
        "\tKind kind;",
        "\tconst char *ref, *label;",
        "\tbool switchBoard;",
        "\tfloat cx, cy;",
        "\tfloat ax, ay, bx, by;",
        "\tfloat qx, qy;",
        "\tfloat size;",
        "\tchar dir;",
        "\tfloat tx, ty;",
        "\tint rot;",
        "};",
        "",
        "inline const Part parts[] = {",
        *[row(p) for p in parts],
        "};",
        "",
        "// The boards' edges, x, y pairs in order.",
        *outlines,
        "",
        "} // namespace board",
        "",
    ]
    open(out, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
